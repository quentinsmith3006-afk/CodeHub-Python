package FirstPythonMeeting.highlevel;

public class Conditional {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        if (a < b) {
            System.out.println("a is less than b");
        } else {
            System.out.println("a is greater than or equal to b");
        }
    }
}
